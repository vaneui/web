// Registry emitters for the docs build pipeline.
//
// The wrappers of one docs page are bundled into one module of their own
// (_pages/<slug>.tsx), and registry.ts maps each page slug to a `next/dynamic`
// loader for that module. A docs page therefore downloads its own demos only.
// A single barrel of static imports put every demo of every page into the
// JavaScript of each docs page.
//
// `next/dynamic` renders the demos on the server and preloads the page's chunk,
// so the HTML carries the demos and hydration finds the chunk already requested.

const HEADER = '// AUTO-GENERATED by scripts/build-examples.mjs — do not edit.\n';

/**
 * Directory of the per-page modules, relative to the wrappers' directory. The
 * leading underscore makes it a private folder, which the App Router keeps out
 * of routing: the modules are named after page slugs, and a slug that is also
 * a route file name (`icon`, `page`, `layout`, ...) would otherwise become a
 * route (`icon.tsx` is the icon metadata route) and fail the build.
 */
export const PAGES_DIR = '_pages';

/**
 * Convert a registry key like "button-basic-usage" into a valid JS identifier
 * `Example_button_basic_usage` (kebab → underscore, prefixed for clarity).
 *
 * @param {string} key
 */
export function toIdent(key) {
  return 'Example_' + key.replace(/[^a-zA-Z0-9_]/g, '_');
}

/**
 * Group wrapper keys by the page slug they belong to, slugs and keys sorted so
 * the emitted files are deterministic.
 *
 * @param {Array<{ slug: string, key: string }>} wrappers
 * @returns {Map<string, string[]>}
 */
export function groupByPage(wrappers) {
  /** @type {Map<string, string[]>} */
  const pages = new Map();
  for (const { slug, key } of wrappers) {
    const keys = pages.get(slug);
    if (keys) keys.push(key);
    else pages.set(slug, [key]);
  }
  return new Map(
    [...pages.keys()].sort().map((slug) => [slug, pages.get(slug).sort()]),
  );
}

/**
 * The module holding one page's wrappers: static imports of that page's
 * wrappers only, and a default-exported component that renders the one named
 * by `id` (`fallback` when the page has no such demo). Lives in PAGES_DIR, one
 * level below the wrappers.
 *
 * @param {string[]} keys wrapper keys (`<slug>-<fenceId>`), which are also the wrapper file names
 * @returns {string}
 */
export function renderPageRegistry(keys) {
  const imports = keys
    .map((k) => `import ${toIdent(k)} from ${JSON.stringify(`../${k}`)};`)
    .join('\n');
  const entries = keys
    .map((k) => `  ${JSON.stringify(k)}: ${toIdent(k)},`)
    .join('\n');
  return (
    HEADER +
    "'use client';\n" +
    "import * as React from 'react';\n" +
    imports +
    '\n\nconst demos: Record<string, React.ComponentType> = {\n' +
    entries +
    '\n};\n\n' +
    'export default function PageDemos({ id, fallback = null }: { id: string; fallback?: React.ReactNode }) {\n' +
    '  const Demo = demos[id];\n' +
    '  return Demo ? <Demo /> : <>{fallback}</>;\n' +
    '}\n'
  );
}

/**
 * The registry: page slug -> lazily loaded demos of that page. Every loader is
 * a literal `import()` at module level, which is what lets the bundler split
 * one chunk per page and lets `next/dynamic` preload it.
 *
 * @param {string[]} slugs page slugs that have at least one wrapper
 * @returns {string}
 */
export function renderRegistry(slugs) {
  const header =
    HEADER +
    "'use client';\n" +
    "import dynamic from 'next/dynamic';\n" +
    "import type { ComponentType, ReactNode } from 'react';\n\n" +
    'export interface PageDemosProps {\n' +
    '  /** Wrapper key: `<page slug>-<fence id>` */\n' +
    '  id: string;\n' +
    '  /** Rendered when the page has no demo with that key */\n' +
    '  fallback?: ReactNode;\n' +
    '}\n\n';

  if (slugs.length === 0) {
    return header + 'export const pageDemos: Record<string, ComponentType<PageDemosProps>> = {};\n';
  }

  const entries = slugs
    .map((slug) => `  ${JSON.stringify(slug)}: dynamic(() => import(${JSON.stringify(`./${PAGES_DIR}/${slug}`)})),`)
    .join('\n');
  return (
    header +
    'export const pageDemos: Record<string, ComponentType<PageDemosProps>> = {\n' +
    entries +
    '\n};\n'
  );
}
